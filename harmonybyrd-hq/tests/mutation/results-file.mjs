/**
 * What tests/mutation/RESULTS.txt says, and when it is written (used by run.mjs).
 *
 * Only a full run (no mutation named) writes the file, and its first line says which code it ran
 * against: the commit (git rev-parse HEAD), "with uncommitted changes" when git status is not clean,
 * the date (UTC) and the number of mutations.
 */
import { spawnSync } from "node:child_process";

/** The commit the working tree is on, and whether it has uncommitted changes. commit is null without git. */
export function codeUnderTest(repo) {
  const head = spawnSync("git", ["rev-parse", "HEAD"], { cwd: repo, encoding: "utf8" });
  if (head.status !== 0 || !head.stdout.trim()) return { commit: null, dirty: false };
  const status = spawnSync("git", ["status", "--porcelain"], { cwd: repo, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
  return { commit: head.stdout.trim(), dirty: status.status !== 0 || status.stdout.trim() !== "" };
}

/** A run with no mutation named is a full run; only a full run writes RESULTS.txt. */
export function shouldWriteResults(wanted) {
  return wanted.length === 0;
}

/** The whole text of RESULTS.txt. */
export function resultsText({ lines, summary, code, date, count }) {
  const on = code.commit
    ? `commit ${code.commit}${code.dirty ? " with uncommitted changes" : ""}`
    : "an unknown commit (git could not be asked)";
  return [
    `Run on ${on}, ${date.toISOString().slice(0, 10)}, ${count} mutation${count === 1 ? "" : "s"}.`,
    "Mutation check of the database tests — generated by `npm run test:mutation`. Do not edit by hand.",
    "Each line: the mutation (one database protection deliberately removed) → how many tests then fail, and the first of them.",
    "",
    ...lines,
    "",
    summary,
    "",
  ].join("\n");
}
