/**
 * Run every automated check and record what actually happened.
 *
 *   npm run test:all                 type check, unit, database, build, HTTP (REST + MCP), browser
 *   npm run test:all -- --no-e2e     leave out the browser suite
 *
 * Writes
 *   test-results/summary.json        machine-readable counts, failures, skipped tests, log checksums
 *   test-results/logs/<suite>.log    the full console output of each suite
 *   docs/TEST-RESULTS.md             the same results as a readable report
 *
 * The report is generated from the reporters' own JSON output. A failing or skipped test is
 * listed by name; nothing is summarised away. The exit code is non-zero if anything failed.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { loadEnv, projectRoot } from "./lib/env";
import { gitInfo, RESULTS_DIR, runCommandSuite, runPlaywright, runVitest, type SuiteResult } from "./lib/suites";

loadEnv();
const root = projectRoot();
const skipE2e = process.argv.includes("--no-e2e");
mkdirSync(path.join(root, RESULTS_DIR, "logs"), { recursive: true });

const startedAt = new Date().toISOString();
const suites: SuiteResult[] = [];
const say = (s: SuiteResult) => console.log(`${s.failed === 0 ? "ok  " : "FAIL"} ${s.title}: ${s.passed} passed, ${s.failed} failed, ${s.skipped} skipped (${s.duration_s}s)`);
const add = (s: SuiteResult) => {
  suites.push(s);
  say(s);
  return s;
};

add(runCommandSuite("typecheck", "TypeScript type check", "npx", ["tsc", "--noEmit"]));
add(runVitest("unit", "Unit tests", "unit"));
add(runVitest("db", "Database tests (governance, security, provenance)", "db"));
const build = add(runCommandSuite("build", "Production build", "npx", ["next", "build"]));
if (build.failed === 0) {
  add(runVitest("api", "HTTP tests (REST and MCP)", "api"));
  if (!skipE2e) add(runPlaywright("e2e", "Browser tests (Playwright, Chromium)"));
} else {
  console.log("The build failed, so the HTTP and browser suites were not run.");
}

const NOT_RUN: { key: string; title: string; reason: string }[] = [];
if (build.failed !== 0) {
  NOT_RUN.push({ key: "api", title: "HTTP tests (REST and MCP)", reason: "the production build failed" });
  NOT_RUN.push({ key: "e2e", title: "Browser tests", reason: "the production build failed" });
} else if (skipE2e) {
  NOT_RUN.push({ key: "e2e", title: "Browser tests", reason: "left out with --no-e2e" });
}

const git = gitInfo();
const totals = suites.reduce((t, s) => ({ passed: t.passed + s.passed, failed: t.failed + s.failed, skipped: t.skipped + s.skipped }), { passed: 0, failed: 0, skipped: 0 });
const summary = {
  generated_at: new Date().toISOString(),
  started_at: startedAt,
  git,
  node: process.version,
  platform: `${process.platform} ${process.arch}`,
  dataset: "synthetic fixture pack (data/packs/fixture)",
  totals,
  suites: Object.fromEntries(suites.map((s) => [s.key, { ...s, summary: `${s.passed} passed, ${s.failed} failed, ${s.skipped} skipped.` }])),
  not_run: NOT_RUN,
};
writeFileSync(path.join(root, RESULTS_DIR, "summary.json"), `${JSON.stringify(summary, null, 2)}\n`);

const lines: string[] = [];
lines.push("# Test results");
lines.push("");
lines.push("Generated by `npm run test:all` (scripts/run-all-tests.ts). Do not edit by hand: re-run the command.");
lines.push("");
lines.push(`- Run finished: ${summary.generated_at}`);
lines.push(`- Source revision: ${git.commit ?? "unknown"}${git.dirty ? " **plus uncommitted changes**" : ""} (branch ${git.branch ?? "unknown"})`);
lines.push(`- Node ${process.version} on ${summary.platform}; PostgreSQL test database \`hq_test\`; data: the synthetic fixture pack`);
lines.push(`- Who ran it: the HQ builder, in the build environment. Nobody else has re-run these suites.`);
lines.push("");
lines.push(`**Total: ${totals.passed} passed, ${totals.failed} failed, ${totals.skipped} skipped.**`);
lines.push("");
lines.push("A passing suite shows that the checks below passed on this revision. It is not a founder acceptance of HQ.");
lines.push("");
lines.push("| Suite | Passed | Failed | Skipped | Time | Command |");
lines.push("| --- | ---: | ---: | ---: | ---: | --- |");
for (const s of suites) lines.push(`| ${s.title} | ${s.passed} | ${s.failed} | ${s.skipped} | ${s.duration_s}s | \`${s.command}\` |`);
for (const n of NOT_RUN) lines.push(`| ${n.title} | — | — | — | — | not run: ${n.reason} |`);
lines.push("");
lines.push("## Failures");
lines.push("");
const failures = suites.flatMap((s) => s.failures.map((f) => `- **${s.title}** — ${f}`));
lines.push(failures.length ? failures.join("\n") : "None.");
lines.push("");
lines.push("## Skipped tests");
lines.push("");
const skipped = suites.flatMap((s) => s.skipped_tests.map((f) => `- **${s.title}** — ${f}`));
lines.push(skipped.length ? skipped.join("\n") : "None.");
lines.push("");
lines.push("## Not covered by any automated test");
lines.push("");
lines.push("See docs/TESTING.md, “What is not tested”. In short: no connection from the Claude or ChatGPT applications, no live GitHub or Google Drive content, no Supabase-hosted deployment, no browser other than Chromium, no load test.");
lines.push("");
lines.push("## Every test, by suite");
for (const s of suites) {
  lines.push("");
  lines.push(`### ${s.title} — ${s.passed} passed, ${s.failed} failed, ${s.skipped} skipped`);
  lines.push("");
  lines.push(`Log: \`${s.log_file}\`${s.log_sha256 ? ` (SHA-256 \`${s.log_sha256}\`)` : ""}`);
  lines.push("");
  for (const o of s.outcomes) lines.push(`- ${o.status === "passed" ? "pass" : o.status === "failed" ? "**FAIL**" : "skip"} — ${o.name}`);
}
lines.push("");
writeFileSync(path.join(root, "docs", "TEST-RESULTS.md"), lines.join("\n"));

console.log(`\nTotal: ${totals.passed} passed, ${totals.failed} failed, ${totals.skipped} skipped.`);
console.log(`Report: docs/TEST-RESULTS.md   Data: ${RESULTS_DIR}/summary.json`);
process.exit(totals.failed === 0 && build.failed === 0 ? 0 : 1);
